    page.get_by_role('tab',name='习惯',exact=True).click()
    expect(page.get_by_text('阅读十分钟',exact=True)).to_be_visible()
    page.get_by_role('button',name='编辑',exact=True).click()
    page.get_by_role('textbox',name='名称',exact=True).fill('阅读十五分钟')
    page.get_by_role('button',name='保存',exact=True).click()
    expect(page.get_by_text('阅读十五分钟',exact=True)).to_be_visible()
    assert not errors,errors
    print('PASS: create/edit habit, half/full check-in, journal, reward redemption, stats, four languages, exemption, reload persistence, CSV and reset preserving templates; no browser runtime errors')
    browser.close()
