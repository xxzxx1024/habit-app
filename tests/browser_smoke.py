from playwright.sync_api import sync_playwright, expect
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':393,'height':852},locale='zh-CN')
    errors=[]
    page.on('pageerror',lambda error:errors.append(str(error)))
    page.on('dialog',lambda dialog:dialog.accept())
    page.goto('http://127.0.0.1:8765')
    page.get_by_role('tab',name='习惯',exact=True).click()
    page.get_by_role('button',name='新增',exact=True).click()
    page.get_by_role('textbox',name='名称',exact=True).fill('阅读十分钟')
    page.get_by_role('textbox',name='单次积分（正整数）',exact=True).fill('5')
    page.get_by_role('textbox',name='每日次数上限',exact=True).fill('3')
    page.get_by_role('switch',name='允许半完成（50%积分）').click()
    page.get_by_role('button',name='保存',exact=True).click()
    expect(page.get_by_text('阅读十分钟',exact=True)).to_be_visible()
    page.get_by_role('tab',name='今日',exact=True).click()
    page.get_by_role('button',name='半完成',exact=True).click()
    expect(page.get_by_text('+2.5 / 30',exact=True)).to_be_visible()
    page.get_by_role('button',name='阅读十分钟 打卡日志',exact=True).click()
    page.get_by_text('半完成',exact=False).last.click()
    page.get_by_role('textbox',name='打卡日志',exact=True).fill('今天读了一半 / half done')
    page.get_by_role('button',name='保存',exact=True).click()
    expect(page.get_by_text('今天读了一半 / half done',exact=True)).to_be_visible()
    page.get_by_role('button',name='关闭',exact=True).click()
    page.get_by_role('button',name='打卡',exact=True).click()
    expect(page.get_by_text('+7.5 / 30',exact=True)).to_be_visible()
    page.screenshot(path='/tmp/habits-home-populated.png')
    page.get_by_role('tab',name='奖励',exact=True).click()
    page.get_by_role('button',name='新增',exact=True).click()
    page.get_by_role('textbox',name='名称',exact=True).fill('一杯咖啡')
    page.get_by_role('textbox',name='兑换所需积分',exact=True).fill('5')
    page.get_by_role('button',name='保存',exact=True).click()
    page.get_by_role('button',name='兑换',exact=True).click()
    expect(page.get_by_text('积分不足，暂时无法兑换',exact=True)).to_be_disabled()
    page.get_by_role('tab',name='统计',exact=True).click()
    expect(page.get_by_text('今天读了一半 / half done',exact=True)).to_be_visible()
    page.screenshot(path='/tmp/habits-stats.png')
    page.get_by_role('tab',name='设置',exact=True).click()
    page.get_by_role('button',name='立即同步',exact=True).click()
    expect(page.get_by_text('iCloud 不可用：',exact=False)).to_be_visible()
    page.get_by_role('button',name='English',exact=True).click()
    expect(page.get_by_text('Point rules',exact=True)).to_be_visible()
    page.get_by_role('button',name='日本語',exact=True).click()
    expect(page.get_by_text('ポイントルール',exact=True)).to_be_visible()
    page.get_by_role('button',name='한국어',exact=True).click()
    expect(page.get_by_text('포인트 규칙',exact=True)).to_be_visible()
    page.get_by_role('button',name='简体中文',exact=True).click()
    page.get_by_role('tab',name='今日',exact=True).click()
    page.get_by_role('button',name='使用豁免卡',exact=True).click()
    expect(page.get_by_text('今日豁免生效中',exact=True)).to_be_visible()
    page.get_by_role('button',name='打卡',exact=True).click()
    expect(page.get_by_text('+7.5 / 30',exact=True)).to_be_visible()
    page.reload()
    page.get_by_role('tab',name='习惯',exact=True).click()
    expect(page.get_by_text('阅读十分钟',exact=True)).to_be_visible()
    page.get_by_role('tab',name='设置',exact=True).click()
    with page.expect_download() as download_info:
        page.get_by_role('button',name='导出 CSV',exact=True).click()
    download=download_info.value
    csv=open(download.path(),encoding='utf-8-sig').read()
    assert '今天读了一半 / half done' in csv and 'redemption' in csv and 'exemption' in csv
    page.get_by_role('button',name='重置打卡与积分',exact=True).click()
    page.get_by_role('tab',name='今日',exact=True).click()
