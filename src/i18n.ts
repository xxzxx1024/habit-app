export function weekdayNames(language: Language): string[] {
  return Array.from({ length: 7 }, (_, i) =>
    new Intl.DateTimeFormat(locale[language], { weekday: 'short' }).format(
      new Date(2024, 0, 7 + i),
    ),
  );
}
